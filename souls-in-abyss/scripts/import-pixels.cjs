// Imports sprites edited in the online pixel editor (souls-in-abyss/docs/pixel-editor.html, cloud saves read
// via ArtifactData into docs/pixels-db/sprites/*.json) into src/ui/pixel-override.ts. Rows and colours are
// copied verbatim; nothing is redrawn here.  Run from souls-in-abyss/:  node scripts/import-pixels.cjs
const fs = require('fs'); const path = require('path');
const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'docs', 'pixels-db', 'sprites');
const PALETTE = { o: '#343842', s: '#667681', h: '#bcc5bd', w: '#e3ddc9', g: '#82947b', G: '#53695e', b: '#839da5', p: '#9586a4', P: '#625575', y: '#c1a775', r: '#b47f76', t: '#ac917b', d: '#725e53', k: '#343842' };
const icons = {}, iconColors = {}, avatars = {};
if (!fs.existsSync(dir)) { console.error('no saves found at', dir); process.exit(1); }
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) {
  const d = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  const doc = d.data ?? d; // ArtifactData wraps {data, version}; accept both
  if (!doc.key || !Array.isArray(doc.rows)) continue;
  const colors = doc.colors || {};
  if (doc.key.startsWith('icon:')) {
    const name = doc.key.slice(5);
    icons[name] = doc.rows.slice(0, 8).map((r) => r.slice(0, 8).padEnd(8, '.'));
    const custom = {};
    for (const [L, hex] of Object.entries(colors)) if (!(L in PALETTE) || PALETTE[L].toLowerCase() !== String(hex).toLowerCase()) custom[L] = String(hex).toLowerCase();
    if (Object.keys(custom).length) iconColors[name] = custom;
  } else if (doc.key.startsWith('avatar:')) {
    const w = Math.max(...doc.rows.map((r) => r.length));
    avatars[doc.key.slice(7)] = { rows: doc.rows.map((r) => r.padEnd(w, '.')), colors: Object.fromEntries(Object.entries(colors).map(([k, v]) => [k, String(v).toLowerCase()])) };
  }
}
let ts = '/** GENERATED by scripts/import-pixels.cjs from the pixel editor\'s cloud saves. Do not edit by hand: edit in the editor and re-import. */\n';
ts += '/** 8-row patterns in the icons.ts letter language; override the built-in pattern of the same name. */\n';
ts += 'export const ICON_PX: Record<string, string[]> = {\n';
for (const [k, rows] of Object.entries(icons)) ts += `  ${JSON.stringify(k)}: [${rows.map((r) => JSON.stringify(r)).join(', ')}],\n`;
ts += '};\n/** Letters whose colour differs from PALETTE (or new letters) for a given icon. */\n';
ts += 'export const ICON_COLORS: Record<string, Record<string, string>> = ' + JSON.stringify(iconColors, null, 2) + ';\n';
ts += '/** Naked 32x48 bodies per race, drawn by the user; gear is still layered on by avatar.ts. */\n';
ts += 'export const AVATAR_PX: Record<string, { rows: string[]; colors: Record<string, string> }> = {\n';
for (const [k, v] of Object.entries(avatars)) ts += `  ${JSON.stringify(k)}: { colors: ${JSON.stringify(v.colors)}, rows: [\n${v.rows.map((r) => `    ${JSON.stringify(r)},`).join('\n')}\n  ] },\n`;
ts += '};\n';
fs.writeFileSync(path.join(root, 'src', 'ui', 'pixel-override.ts'), ts);
console.log('imported', Object.keys(icons).length, 'icons:', Object.keys(icons).join(', ') || '-', '|', Object.keys(avatars).length, 'avatars:', Object.keys(avatars).join(', ') || '-');
