// Imports sprites edited in the online pixel editor (docs/sprites-db/sprites/*.json, read via ArtifactData) into
// src/content/sprites-override.ts. Rows and colours are copied verbatim.  Run: node tests/tools/import-sprites.cjs
const fs = require('fs'); const path = require('path');
const dir = path.join('docs', 'sprites-db', 'sprites');
const out = {};
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) {
  const d = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  const doc = d.data ?? d; // ArtifactData wraps {data, version}; accept both
  if (!doc.key || !Array.isArray(doc.rows)) continue;
  const w = Math.max(...doc.rows.map((r) => r.length));
  out[doc.key] = { rows: doc.rows.map((r) => r.padEnd(w, '.')), colors: doc.colors || {}, updatedAt: doc.updatedAt || 0 };
}
let ts = '/** GENERATED by tests/tools/import-sprites.cjs from the pixel editor\'s cloud saves. Do not edit by hand: edit in the editor and re-import. */\n';
ts += 'export const SPRITE_PX: Record<string, { rows: string[]; colors: Record<string, string> }> = {\n';
for (const [k, v] of Object.entries(out)) ts += `  ${JSON.stringify(k)}: { colors: ${JSON.stringify(v.colors)}, rows: [\n${v.rows.map((r) => `    ${JSON.stringify(r)},`).join('\n')}\n  ] },\n`;
ts += '};\n';
fs.writeFileSync('src/content/sprites-override.ts', ts);
console.log('imported', Object.keys(out).length, 'sprites:', Object.keys(out).join(', '));
