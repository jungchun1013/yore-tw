import { type C, INK, TAU, bigEye, blob, blush, curve, dot, ell, eyes, flame, fs, glow, line, poly, rr, smile, tongue } from './kit';

type Draw = (c: C) => void;
export interface YokaiArt { w: number; h: number; draw: Draw }

const brows = (c: C, x: number, y: number, gap: number, len: number, tilt: number, lw = 2): void => {
  line(c, [x - gap - len, y - tilt, x - gap + len, y + tilt], INK, lw);
  line(c, [x + gap - len, y + tilt, x + gap + len, y - tilt], INK, lw);
};

function ribs(c: C, x: number, y: number, rx: number, ry: number, n: number, col: string): void {
  for (let i = 1; i <= n; i++) {
    const t = -1 + (2 * i) / (n + 1), yy = y + t * ry, w = rx * Math.sqrt(1 - t * t);
    curve(c, x - w, yy, x, yy + 2.2, x + w, yy, col, 1.3);
  }
}

