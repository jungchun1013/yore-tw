// Visual state only: spawning, damage, targeting and wave timing stay in the engine.
export class BossLighting {
  constructor() { this.amount = 0; this.active = false; }
  update(game, dt) {
    this.active = game.state === 'running' && game.enemies.some(e => e.kind === 'boss' && !e.dead);
    const target = this.active ? 1 : 0;
    const step = Math.max(0, dt) / (this.active ? .9 : 1.3);
    this.amount = this.active ? Math.min(target, this.amount + step) : Math.max(target, this.amount - step);
  }
  get strength() { return this.amount * this.amount * (3 - 2 * this.amount); }
}

